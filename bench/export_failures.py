"""Export every system's failed cases into failures/ (kept in git), so errors can be studied and fixed in general.

  .venv/bin/python bench/export_failures.py

The aim is to find *general* weaknesses (reading order, old scans, tables, loops...) and fix them with changes that
make sense for any document. Do not tune against these lists: they come from the benchmarks we report.

Writes
  failures/olmocr/<system>.jsonl          every failed olmOCR-Bench test (scorer's explanation included)
  failures/olmocr/outputs/<system>/...    that system's markdown for every page with a failed test
  failures/omnidocbench/<system>.jsonl    per-page OmniDocBench errors (text/formula/order edit, worst table TEDS)
  failures/omnidocbench/outputs/<system>/ markdown for pages with text edit > 0.2, order edit > 0.3 or a table TEDS < 0.5
  failures/SUMMARY.md                     counts by category and test type, plus pages every system fails
"""
import collections
import glob
import json
import os
import shutil

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
R = os.path.join(ROOT, "results")
OUT = os.path.join(ROOT, "failures")
# system name in the docs -> (olmOCR-Bench run, OmniDocBench run)
SYSTEMS = {
    "v1": ("pipe_mask_lp", "omni_mask_lp"),
    "v2": ("v2", "omni_v2"),
    "c3b_sota": ("modal_c3b_olmocr", "modal_c3b_omni"),  # end to end on Modal
    "c3b_offline": ("c3b", "omni_c3b"),
    "ltpro1": ("ltpro1", "omni_ltpro1"),
    "casc20": ("casc20", "omni_casc20"),
    "lightonocr3_4b_u": ("lt4_u", "omni_lt4_u"),
    "infinity_pro": ("inf_pro", None),
    "infinity_flash": ("inf_flash", "omni_inf_flash"),
}
OUTPUT_SYSTEMS = {"v2", "c3b_sota"}  # markdown outputs exported for these


def olmocr(name, key, summary):
    fails = [json.loads(l) for l in open(os.path.join(R, key, "_failures.jsonl"))]
    os.makedirs(os.path.join(OUT, "olmocr"), exist_ok=True)
    with open(os.path.join(OUT, "olmocr", f"{name}.jsonl"), "w") as f:
        f.writelines(json.dumps(x, ensure_ascii=False) + "\n" for x in fails)
    cnt = collections.Counter((x.get("category") or x["pdf"].split("/")[0], x["type"]) for x in fails)
    summary["olmocr"][name] = (len(fails), cnt)
    pages = sorted({x["pdf"] for x in fails})
    if name in OUTPUT_SYSTEMS:
        for p in pages:
            src = os.path.join(R, key, os.path.splitext(p)[0] + "_pg1_repeat1.md")
            dst = os.path.join(OUT, "olmocr", "outputs", name, os.path.splitext(p)[0] + ".md")
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            if os.path.exists(src):
                shutil.copy(src, dst)
    return {x["pdf"] for x in fails}


def omni(name, key, summary):
    if not key or not os.path.isdir(os.path.join(R, key, "_omni_pp")):
        return
    pp = os.path.join(R, key, "_omni_pp")
    metric = {}
    for f in glob.glob(os.path.join(pp, "*.json")):
        kind = os.path.basename(f)[len(key) + len("_quick_match_"):-len(".json")]
        metric[kind] = json.load(open(f))
    pages = collections.defaultdict(dict)
    for kind, field in [("text_block_per_page_edit", "text_edit"), ("display_formula_per_page_edit", "formula_edit"),
                        ("reading_order_per_page_edit", "order_edit"), ("table_per_page_edit", "table_edit")]:
        for p, v in (metric.get(kind) or {}).items():
            pages[p][field] = v
    for k, v in (metric.get("table_per_table_TEDS") or {}).items():  # keys look like "<page>.png_[0]"
        p = k.rsplit("_[", 1)[0]
        teds = v["TEDS"] if isinstance(v, dict) else v
        pages[p]["min_table_teds"] = round(min(teds, pages[p].get("min_table_teds", 1.0)), 4)
    os.makedirs(os.path.join(OUT, "omnidocbench"), exist_ok=True)
    rows = sorted(({"page": p, **m} for p, m in pages.items()), key=lambda r: -r.get("text_edit", 0))
    with open(os.path.join(OUT, "omnidocbench", f"{name}.jsonl"), "w") as f:
        f.writelines(json.dumps(r) + "\n" for r in rows)
    bad = [r for r in rows if r.get("text_edit", 0) > 0.2 or r.get("order_edit", 0) > 0.3
           or r.get("min_table_teds", 1) < 0.5]
    summary["omni"][name] = (len(rows), len(bad), rows[:10])
    if name in OUTPUT_SYSTEMS:
        for r in bad:
            src = os.path.join(R, key, os.path.splitext(r["page"])[0] + ".md")
            dst = os.path.join(OUT, "omnidocbench", "outputs", name, os.path.splitext(r["page"])[0] + ".md")
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            if os.path.exists(src):
                shutil.copy(src, dst)


def main():
    if os.path.isdir(OUT):
        shutil.rmtree(OUT)
    summary = {"olmocr": {}, "omni": {}}
    failed_pages = {}
    for name, (ok, om) in SYSTEMS.items():
        failed_pages[name] = olmocr(name, ok, summary)
        omni(name, om, summary)
    L = ["# Failed cases", "",
         "Generated by `bench/export_failures.py`. Use these to find *general* weaknesses and fix them in ways that make",
         "sense for any document. Do not tune against them: they are the benchmarks we report.", "",
         "Inputs: olmOCR-Bench PDFs are in `data/olmOCR-bench/bench_data/pdfs/<category>/` (download: `allenai/olmOCR-bench`);",
         "OmniDocBench images come from `opendatalab/OmniDocBench` (`images/`).", "",
         "## olmOCR-Bench: failed tests by category and test type", ""]
    for name, (n, cnt) in summary["olmocr"].items():
        L.append(f"### {name} ({n} failed tests)")
        cats = sorted({c for c, _ in cnt})
        types = sorted({t for _, t in cnt})
        L.append("| category | " + " | ".join(types) + " |")
        L.append("|---" * (len(types) + 1) + "|")
        for c in cats:
            L.append(f"| {c} | " + " | ".join(str(cnt.get((c, t), "")) for t in types) + " |")
        L.append("")
    common = set.intersection(*failed_pages.values())
    L += [f"### Pages with a failed test in every system ({len(common)})", "",
          "Hard for every reader we tried; the best place to look for a missing capability.", ""]
    L += [f"- `{p}`" for p in sorted(common)]
    L += ["", "## OmniDocBench: worst pages by text edit distance", "",
          "Bad page = text edit > 0.2, reading-order edit > 0.3 or a table TEDS < 0.5.", ""]
    for name, (n, nbad, top) in summary["omni"].items():
        L.append(f"### {name}: {nbad} bad pages of {n}")
        L.append("| page | text_edit | formula_edit | order_edit | min_table_teds |")
        L.append("|---|---|---|---|---|")
        for r in top:
            L.append(f"| {r['page']} | {r.get('text_edit', '')} | {r.get('formula_edit', '')} | "
                     f"{r.get('order_edit', '')} | {r.get('min_table_teds', '')} |")
        L.append("")
    open(os.path.join(OUT, "SUMMARY.md"), "w").write("\n".join(L) + "\n")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
